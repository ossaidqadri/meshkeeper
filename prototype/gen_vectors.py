"""Write fixed WSC test vectors for the Zig port to src/testdata/wsc_vectors.zig.

The Python M2 builder is the one a real TP-Link AX12 accepted, so the Zig
implementation must reproduce its output byte for byte from the same inputs.
Run: uv run python gen_vectors.py
"""

import hashlib
from pathlib import Path

import wsc
from test_wsc import make_m1


def det(label: str, n: int) -> bytes:
    """Deterministic pseudo-random bytes so vectors are reproducible."""
    out = b""
    i = 0
    while len(out) < n:
        out += hashlib.sha256(f"{label}:{i}".encode()).digest()
        i += 1
    return out[:n]


CASES = [
    ("5ghz_8char", wsc.RF_BAND_5, wsc.BssConfig(ssid="MK 5GHz Ext", passphrase="exactly8")),
    ("24ghz_long", wsc.RF_BAND_24, wsc.BssConfig(ssid="MK Ext", passphrase="a-much-longer-passphrase-of-40-chars-ok!")),
]


def main() -> None:
    lines = [
        "// Generated by prototype/gen_vectors.py. Do not edit.",
        "pub const Case = struct { name: []const u8, rf_bands: u8, ssid: []const u8, passphrase: []const u8,",
        "    m1: []const u8, registrar_priv: []const u8, registrar_nonce: []const u8, registrar_uuid: []const u8, iv: []const u8, m2: []const u8 };",
        "",
        "pub const cases = [_]Case{",
    ]
    for name, band, bss in CASES:
        enrollee_priv = int.from_bytes(det(f"{name}:enrollee", wsc.DH_LEN), "big") % (wsc.DH_P - 2) + 1
        m1_raw = make_m1(enrollee_priv, bytes.fromhex("020000a0d950"), det(f"{name}:enonce", 16), band)
        # make_m1 puts a random UUID-E in; pin it so the vector is stable.
        m1_raw = m1_raw.replace(m1_raw[m1_raw.index(b"\x10\x47") + 4 : m1_raw.index(b"\x10\x47") + 20], det(f"{name}:uuid-e", 16), 1)
        m1 = wsc.parse_m1(m1_raw)
        priv = int.from_bytes(det(f"{name}:registrar", wsc.DH_LEN), "big") % (wsc.DH_P - 2) + 1
        nonce, uuid, iv = det(f"{name}:rnonce", 16), det(f"{name}:ruuid", 16), det(f"{name}:iv", 16)
        m2 = wsc.build_m2(m1, bss, uuid, priv=priv, registrar_nonce=nonce, iv=iv)
        lines += [
            "    .{",
            f'        .name = "{name}", .rf_bands = {band}, .ssid = "{bss.ssid}", .passphrase = "{bss.passphrase}",',
            f'        .m1 = "{m1_raw.hex()}",',
            f'        .registrar_priv = "{priv.to_bytes(wsc.DH_LEN, "big").hex()}",',
            f'        .registrar_nonce = "{nonce.hex()}", .registrar_uuid = "{uuid.hex()}", .iv = "{iv.hex()}",',
            f'        .m2 = "{m2.hex()}",',
            "    },",
        ]
    lines.append("};")
    out = Path(__file__).resolve().parent.parent / "src" / "testdata" / "wsc_vectors.zig"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(CASES)} cases to {out}")


if __name__ == "__main__":
    main()
